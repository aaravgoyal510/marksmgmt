/**
 * Sanitizes user-submitted text input to prevent Stored XSS and HTML/script injection.
 */
export function sanitizeTextInput(input: string): string {
  if (typeof input !== "string") return input;

  return input
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#x27;")
    .replace(/\//g, "&#x2F;");
}
